create table if not exists public.game_players (
  id bigint generated by default as identity primary key,
  nickname text not null unique,
  created_at timestamptz not null default now(),
  constraint game_players_nickname_length_check check (char_length(btrim(nickname)) between 2 and 24)
);

create table if not exists public.game_results (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.game_players(id) on delete cascade,
  game_key text not null,
  difficulty text,
  score integer,
  combo integer,
  duration_seconds integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint game_results_game_key_check check (game_key in ('minesweeper', 'brick_breaker', 'neon_flow')),
  constraint game_results_difficulty_check check (
    (game_key = 'minesweeper' and difficulty in ('easy', 'medium', 'hard'))
    or
    (game_key = 'brick_breaker' and difficulty is null)
    or
    (game_key = 'neon_flow' and difficulty in ('easy', 'medium', 'hard', 'expert'))
  ),
  constraint game_results_non_negative_check check (
    coalesce(score, 0) >= 0
    and coalesce(combo, 0) >= 0
    and coalesce(duration_seconds, 0) >= 0
  ),
  constraint game_results_required_values_check check (
    (game_key = 'minesweeper' and duration_seconds is not null and score is null and combo is null)
    or
    (game_key = 'brick_breaker' and score is not null and combo is not null and duration_seconds is null)
    or
    (game_key = 'neon_flow' and score is not null and duration_seconds is not null and combo is null)
  )
);

