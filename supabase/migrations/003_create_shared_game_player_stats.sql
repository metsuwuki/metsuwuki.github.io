drop policy if exists "Game players are readable" on public.game_players;
create policy "Game players are readable"
  on public.game_players for select
  using (true);

drop policy if exists "Anyone can create game players" on public.game_players;
create policy "Anyone can create game players"
  on public.game_players for insert
  with check (char_length(btrim(nickname)) between 2 and 24);

drop policy if exists "Game results are readable" on public.game_results;
create policy "Game results are readable"
  on public.game_results for select
  using (true);

drop policy if exists "Anyone can create game results" on public.game_results;
create policy "Anyone can create game results"
  on public.game_results for insert
  with check (
    exists (
      select 1
      from public.game_players
      where game_players.id = game_results.player_id
    )
    and game_key in ('minesweeper', 'brick_breaker', 'neon_flow')
    and (
      (game_key = 'minesweeper' and difficulty in ('easy', 'medium', 'hard'))
      or
      (game_key = 'brick_breaker' and difficulty is null)
      or
      (game_key = 'neon_flow' and difficulty in ('easy', 'medium', 'hard', 'expert'))
    )
    and coalesce(score, 0) >= 0
    and coalesce(combo, 0) >= 0
    and coalesce(duration_seconds, 0) >= 0
  );

