create or replace view public.minesweeper_leaderboard
with (security_invoker = true) as
select
  min(gr.id) as id,
  gp.nickname,
  gr.difficulty,
  min(gr.duration_seconds) as time_seconds,
  count(*)::integer as games_played,
  min(gr.created_at) as created_at,
  max(gr.created_at) as updated_at
from public.game_results gr
join public.game_players gp on gp.id = gr.player_id
where gr.game_key = 'minesweeper'
group by gp.id, gp.nickname, gr.difficulty;

create or replace view public.brick_breaker_leaderboard
with (security_invoker = true) as
select
  min(gr.id) as id,
  gp.nickname,
  max(gr.score) as score,
  max(gr.combo) as best_combo,
  count(*)::integer as games_played,
  min(gr.created_at) as created_at,
  max(gr.created_at) as updated_at
from public.game_results gr
join public.game_players gp on gp.id = gr.player_id
where gr.game_key = 'brick_breaker'
group by gp.id, gp.nickname;

create or replace view public.neon_flow_leaderboard
with (security_invoker = true) as
select distinct on (gp.id, gr.difficulty)
  gp.nickname,
  gr.difficulty,
  gr.score as best_score,
  gr.duration_seconds as best_time_seconds,
  coalesce((gr.metadata->>'moves')::integer, 0) as best_moves,
  count(*) over (partition by gp.id, gr.difficulty)::integer as games_played,
  gr.created_at
from public.game_results gr
join public.game_players gp on gp.id = gr.player_id
where gr.game_key = 'neon_flow'
order by gp.id, gr.difficulty, gr.score desc, gr.duration_seconds asc, coalesce((gr.metadata->>'moves')::integer, 0) asc, gr.created_at asc;

create or replace view public.player_global_stats
with (security_invoker = true) as
select
  gp.id,
  gp.nickname,
  count(gr.id)::integer as total_games_played,
  count(gr.id) filter (where gr.game_key = 'minesweeper')::integer as minesweeper_games_played,
  min(gr.duration_seconds) filter (where gr.game_key = 'minesweeper' and gr.difficulty = 'easy') as minesweeper_easy_best_seconds,
  min(gr.duration_seconds) filter (where gr.game_key = 'minesweeper' and gr.difficulty = 'medium') as minesweeper_medium_best_seconds,
  min(gr.duration_seconds) filter (where gr.game_key = 'minesweeper' and gr.difficulty = 'hard') as minesweeper_hard_best_seconds,
  count(gr.id) filter (where gr.game_key = 'brick_breaker')::integer as brick_breaker_games_played,
  coalesce(max(gr.score) filter (where gr.game_key = 'brick_breaker'), 0) as brick_breaker_best_score,
  coalesce(max(gr.combo) filter (where gr.game_key = 'brick_breaker'), 0) as brick_breaker_best_combo,
  count(gr.id) filter (where gr.game_key = 'neon_flow')::integer as neon_flow_games_played,
  coalesce(max(gr.score) filter (where gr.game_key = 'neon_flow'), 0) as neon_flow_best_score,
  gp.created_at,
  coalesce(max(gr.created_at), gp.created_at) as updated_at
from public.game_players gp
left join public.game_results gr on gr.player_id = gp.id
group by gp.id, gp.nickname, gp.created_at;

create index if not exists game_players_nickname_idx on public.game_players (lower(nickname));
