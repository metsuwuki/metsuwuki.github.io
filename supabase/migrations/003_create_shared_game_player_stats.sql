create index if not exists game_results_brick_breaker_idx on public.game_results (score desc, combo desc) where game_key = 'brick_breaker';
create index if not exists game_results_neon_flow_idx on public.game_results (difficulty, score desc, duration_seconds) where game_key = 'neon_flow';

